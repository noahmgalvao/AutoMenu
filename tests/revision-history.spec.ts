import { test, expect } from '@playwright/test';
for (const width of [393, 1280]) {
    test(`history ${width}px: metadata-only panel, tabs, inline save, cancel/failure counter and page cursor`, async ({ page }) => {
        await page.setViewportSize({ width, height: 880 });
        await page.goto('/tests/fixtures/revision-history.html');
        const panel = page.getByRole('region', { name: 'Histórico de revisões' });
        await expect(panel).toBeVisible();
        await expect(page.getByTestId('calls')).not.toContainText('load:');
        await expect(page.getByRole('button', { name: 'Salvar versão', exact: true })).toHaveCount(0);
        await expect(page.getByRole('tooltip')).toHaveCount(0);
        await panel.getByRole('button', { name: 'Política do histórico' }).click();
        await expect(page.getByRole('tooltip')).toBeVisible();
        await page.getByTestId('editor').click();
        await expect(page.getByRole('tooltip')).toHaveCount(0);
        await panel.getByRole('button', { name: 'Carregar mais' }).click();
        await expect(page.getByTestId('calls')).toContainText('page:all:36');
        await panel.getByRole('tab', { name: 'Protegidas' }).click();
        const save = panel.getByRole('button', { name: 'Salvar versão', exact: true });
        await expect(save).toBeVisible();
        await save.click();
        await expect(panel.getByLabel('Nome da versão')).toHaveValue('Versão 1');
        await panel.getByRole('button', { name: 'Cancelar', exact: true }).click();
        await save.click();
        await expect(panel.getByLabel('Nome da versão')).toHaveValue('Versão 1');
        await panel.getByLabel('Nome da versão').fill('Falhar');
        await panel.getByRole('button', { name: 'Salvar', exact: true }).click();
        await expect(panel.getByRole('alert')).toContainText('Não foi possível conectar');
        await expect(panel.getByLabel('Nome da versão')).toHaveValue('Falhar');
        await panel.getByLabel('Nome da versão').fill('Minha versão');
        await panel.getByRole('button', { name: 'Salvar', exact: true }).click();
        await expect(panel.getByRole('tab', { name: 'Protegidas' })).toHaveAttribute('aria-selected', 'true');
        await expect(panel.getByRole('button', { name: /Minha versão/ })).toBeVisible();
        await save.click();
        await expect(panel.getByLabel('Nome da versão')).toHaveValue('Versão 2');
        await panel.getByRole('tab', { name: 'Importantes' }).click();
        await expect(save).toHaveCount(0);
        await expect(panel.getByLabel('Nome da versão')).toHaveCount(0);
        await expect(panel).toHaveJSProperty('scrollWidth', await panel.evaluate(el => el.clientWidth));
        await page.screenshot({ path: `/tmp/automenu-history-${width}.png` });
    });
}
test('historical preview uses all real canvas pages, is read-only and restore requires confirmation', async ({ page }) => {
    await page.goto('/tests/fixtures/revision-history.html');
    await page.getByRole('region').getByRole('button', { name: /Revisão 65/ }).click();
    await expect(page.getByRole('dialog', { name: 'Prévia histórica' })).toBeVisible();
    await expect(page.locator('[data-menu-print-page]')).toHaveCount(2);
    await expect(page.getByRole('button', { name: 'Salvar versão', exact: true })).toHaveCount(0);
    await expect(page.getByTestId('calls')).toContainText('load:r64');
    await page.getByRole('button', { name: 'Restaurar', exact: true }).click();
    await expect(page.getByTestId('calls')).not.toContainText('|restore');
    await page.getByRole('button', { name: 'Confirmar', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Publique novamente' })).toBeVisible();
    await expect(page.getByTestId('calls')).toContainText('|restore');
});
test('preview keyboard focus stays in the dialog and rapid cancellation cannot install an older state', async ({ page }) => {
    await page.goto('/tests/fixtures/revision-history.html');
    const panel = page.getByRole('region', { name: 'Histórico de revisões' });
    await panel.getByRole('button', { name: /Revisão 65/ }).click();
    await page.keyboard.press('Escape');
    await expect(panel).toBeVisible();
    await panel.getByRole('button', { name: /Revisão 64/ }).click();
    const dialog = page.getByRole('dialog', { name: 'Prévia histórica' });
    await expect(dialog.getByText('Preview r63', { exact: true })).toBeVisible();
    await page.waitForTimeout(200);
    await expect(dialog.getByText('Preview r64', { exact: true })).toHaveCount(0);
    await dialog.getByRole('button', { name: 'Voltar à versão atual' }).focus();
    await page.keyboard.press('Shift+Tab');
    expect(await dialog.evaluate(el => el.contains(document.activeElement))).toBe(true);
    await page.keyboard.press('Escape');
    await expect(panel).toBeVisible();
});

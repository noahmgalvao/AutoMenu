import { PRESET_TEMPLATES, CATALOG_VERSION } from '../src/domain/templates/templateCatalog.ts';

// Regenerate the seed after changing the manifest and add a migration for the new version.
const literal = (value) => "'" + value.replaceAll("'", "''") + "'";
const manifest = PRESET_TEMPLATES.map((style) => ({
  id: style.id, name: style.name, version_id: style.templateVersionId,
  metadata: style.catalogMetadata,
  style_state: style,
}));

process.stdout.write(`-- Generated by scripts/generate-template-catalog.mjs from src/domain/templates/templateCatalog.ts.
alter table public.templates add column if not exists catalog_metadata jsonb;
alter table public.templates add column if not exists catalog_active boolean not null default false;

create temporary table automenu_catalog_seed (id text, name text, version_id text, metadata jsonb, style_state jsonb) on commit drop;
insert into automenu_catalog_seed
select * from jsonb_to_recordset(${literal('[\n' + manifest.map((item) => '  ' + JSON.stringify(item)).join(',\n') + '\n]')}::jsonb)
  as catalog(id text, name text, version_id text, metadata jsonb, style_state jsonb);

-- Retain legacy IDs and versions for any previous references.
update public.templates set catalog_active = false where scope = 'system'
  and id not in (select id from automenu_catalog_seed);

insert into public.templates (id, name, scope, source_type, is_locked, catalog_metadata, catalog_active)
select id, name, 'system', 'preset', true, metadata, true from automenu_catalog_seed
on conflict (id) do update set name = excluded.name, catalog_metadata = excluded.catalog_metadata,
  catalog_active = true, is_locked = true where templates.scope = 'system';

insert into public.template_versions (id, template_id, version_number, style_state)
select seed.version_id, seed.id, ${CATALOG_VERSION}, seed.style_state
from automenu_catalog_seed seed join public.templates t on t.id = seed.id and t.scope = 'system'
on conflict (template_id, version_number) do update set style_state = excluded.style_state;

update public.templates t set current_version_id = v.id
from automenu_catalog_seed seed join public.template_versions v on v.template_id = seed.id and v.version_number = ${CATALOG_VERSION}
where t.id = seed.id and t.scope = 'system';
`);
